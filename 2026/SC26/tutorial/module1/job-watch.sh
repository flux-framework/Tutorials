#!/bin/bash
# Prints a poem one line at a time, so that `flux watch` has something to show.

echo "The deep dish takes its forty minutes. Nobody is sorry."
sleep 2
echo "Sit down, and I will pass the time with a Chicago story:"
sleep 2
echo "The river's dyed on Patrick's Day and flows the wrong direction,"
sleep 2
echo "The Bean reflects the skyline, and your very wide reflection."
sleep 2
echo "No ketchup on the hot dog. Please don't ask. They'll know you're new."
sleep 2
echo "The wind will take your hat, your scarf, and your conference badge too."
sleep 2
echo "The L runs round the Loop all day, the Cubs waited one-oh-eight,"
sleep 2
echo "And like a deep dish fresh from the oven, your job was worth the wait."
